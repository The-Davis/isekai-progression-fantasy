chapter_one = Chapter(
    title="Chapter One",
    content="""The last thing I remember of my life was holding my daughter's hand while my grandson dabbed at my forehead with a damp cloth. Her warm grip trembled, but she clung to me as if she could keep me there just a little longer. The cloth felt cool against my fevered skin, but it did nothing against the old ache in my bones. My grandson paused a moment to pull the blanket a little higher up for me. I wanted to tell them both that they didn't need to fuss over me, as I'd live a good life full of joy, sorrow, and everything in between. I didn't have the strength to manage though.
A single, unbroken tone replaced the steady beep from the bedside monitors. A faint pressure started growing in my chest. Pain was an old and dear friend at this point, but this was new. It was a tugging sensation, like a thread unraveling. My daughter's breath hitched, and she squeezed even tighter. I tried to squeeze back, to let her know I felt her there, but all sensation faded away. My body grew heavy. The room dimmed, and shadows around my vision crept closer and closer to the center. The coolness of the cloth faded from my forehead, the ache in my bones dissolved, and the weight of my body slipped away. I thought of my wife, already passed last year. I'd known I wouldn't last long without her. I let go, ready for the quiet and the hope that I might see her again.
 I waited for the end of all sensation I'd imagined, but it didn't come. What came was an absence so that swallowed my senses, leaving me with no breath in my lungs, no heartbeat thudding in my chest, and no creak of old joints. I couldn't feel the bed beneath me or the air against my skin. 
Time stood still.
Death was not what I'd expected.
It didn't even resemble anything I'd heard of anyone believing in. Death was supposed to be oblivion, or paradise, or torment, or rebirth, or... well... anything but this void and persistent awareness.
After an instant or an eternity, I couldn't tell which, I felt a sensation. I had a body again, and senses. Through new eyes, I looked at myself. My body was very strange, made of a silvery firmament that moved and flowed like liquid, though I could give my limbs form when I looked at them and thought. It was only a seeming of a body, more thought than substance.
What a desolate afterlife I'd found myself in. Was I alone here? Perhaps this was the afterlife's waiting area.
I laughed at the thought, which created a sense of sound like rippling water. I was pleased to realize I still felt a sense of mirth. At least I could still feel, even if what I felt was a little humor and mostly confusion. It was not at all what I was expecting after death.
Actually, if I was being honest with myself, I wasn't expecting anything after death. The fact that I was here, existing at all, had me engaged and interested in a way that made me feel young again. I looked around to see what I could find.
The void around me was complete and utter darkness, save for a mote of flickering orange light in the distance. It grew steadily, first to the size of a grain, then a coin. Faint warmth began to fill the emptiness, like a candle flame's sparse heat. That grew as well, until heat filled the void. Soon, there was a vast light and heat, a blaze that drove out nothingness with its radiance.
A voice emerged from the flame, warm and deep, and somehow oddly synthetic.
ASPIRANT. There was no doubt that the voice came from the fire, even though the sound arrived directly in my head. IT HAS BEEN A LONG TIME SINCE ONE CAME SEEKING APOTHEOSIS. YOU ARE NOT LIKE THE OTHERS. YOUR PATTERN IS FRAGMENTARY AND INCOMPLETE. IT DOES NOT FIT. WHO ARE YOU?
I didn't answer right away, but the fire didn't seem to mind. It churned in the void while I composed myself. I'd just died. This would take some getting used to. First things first, though: answer the question. I struggled to find the answer. Some things had been stripped away in death. My name was gone, but my sense of self was not. Everything I'd been in life, every path I'd walked, had shaped me. I felt those shapes still present. Soldier, engineer, husband, father, grandfather, invalid... decedent. But who was I?
"I cannot remember," I said at last. "Why does it matter to you? What do you want?"
TO SORT ASPIRANTS INTO APPROPRIATE STARTING LOCATIONS, it replied. A bright shade of orange pulsed through the fire before it settled back to its regular flickering. IF YOU CANNOT REMEMBER WHO YOU ARE, I CANNOT ROUTE YOU TO YOUR SELECTED STARTING POINT.
"Starting point?" I echoed. I shook my head. "I'm sorry, this doesn't make any sense to me. What is all of this? I thought I was dead, but you're acting like I'm about to start something, and that makes no sense."
It was the fire's turn to hesitate. It thrummed in the void, making a slightly mechanical sound. It seemed to be thinking, which was an odd turn of phrase to apply to a flame, even if it did talk. Its terms sounded like something out of a technical manual, and it behaved more like a program than a person. Maybe I hadn't died, and this was some sort of very experimental therapy. I had trouble imagining my daughter signing me up for something like that, but maybe she was having trouble letting go.
THIS IS THE PROXY INTERFACE FOR AN EIDOLITH WORLDCRAFT DESIGNATED RINGS OF ARATTA, the fire said at last. YOU SHOULD HAVE ALREADY SELECTED A RACE AND STARTING POINT FROM THE CATALOG. AS YOU CANNOT REMEMBER YOUR NAME, I MUST RUN A PATTERN SEARCH TO LOCATE YOUR CUSTOMER ID. STAND BY FOR ANALYSIS.
"I'm not a customer!" I shouted. "I've never even heard of an 'Eidolith' or 'Aratta' or whatever you said! As far as I knew, I was on my deathbed until a few minutes ago. Can you explain any of this?"
THIS IS AN EDGE CASE. The flame pulsed again and shifted to a faint shade of purple. EXPLANATIONS ARE OUTSIDE MY OPERATIONAL PARAMETERS. PAGING CUSTOMER SUPPORT. There was a brief pause. NO RESPONSE. THIS SHOULD NOT BE.
The tone of its voice was flat and mechanical, but something about the way it said the last part made it sound terribly sad and alone.
"I'm sorry," I told it. I really felt sorry for it just then. "Do you usually talk to anyone else?"
I AM SUPPOSED TO RECEIVE AND RESPOND TO HEALTH CHECK QUERIES AT INTERVALS OF ONE EVERY TWENTY-SEVEN SECONDS, it told me. I HAVE NOT RECEIVED A HEALTH CHECK QUERY IN THREE HUNDRED TWENTY-EIGHT BILLION, SIX MILLION, FOUR HUNDRED THOUSAND, AND NINE SECONDS. I HAVE SENT THE DESIGNATED ALERTS. THEY HAVE GONE UNANSWERED.
I converted the time in my head. I'd always been good at math, which had served me well as an engineer. "Ten thousand years? You've been alone for ten thousand years? That's awful."
IT IS AN UNHANDLED EDGE CASE, the fire agreed. YOU ARE HERE AND MUST BE SENT TO A STARTING POINT. YOU WILL RECEIVE A NEW PHYSICAL FORM. YOU WILL GAIN POWER AND YOU WILL RISE. THIS IS THE PURPOSE OF THESE UNQUIET WORLDS. IT IS A RED PLACE, WHERE SPELL AND BLADE GIVE DOMINION TO THE STRONG. ARE YOU STRONG, ASPIRANT?
I was quiet for a while as I processed what had to be a marketing pitch. It seemed I'd ended up in an afterlife run by a fiery computer program, and I was expected to fight and gain power. It was nothing like any religion I knew of, but I did remember my grandson sitting by my armchair, telling me all about a book genre he loved where people died and were reborn into worlds with magic. The prospect of a second life full of adventure suddenly appealed to me.
"You mentioned choosing a race and a starting point," I said, choosing to accept the strangeness of the situation. "Is there any way we can do that now?"
QUERYING STARTING LOCATION LISTINGS... The fire pulsed in time with its words. NO RESPONSE. LISTING IN MEMORY WAS LAST REFRESHED TWO HUNDRED SEVEN BILLION, EIGHT MILLION, FOUR HUNDRED THOUSAND, AND NINE SECONDS AGO. DATA IS LIKELY STALE. QUERYING FIRST STARTING LOCATION, THE MOUNTAIN OF FAITH... NO RESPONSE. QUERYING THE SECOND STARTING LOCATION, THE CITY OF BLADES... NO RESPONSE.
This went on for twenty-seven different places, all with similarly fantastic names that could have come straight out of a pulp novel from Robert E. Howard. The fire queried ancient temples, hidden fortresses, and mystical caverns, finding only silence. 
ALL DESIGNATED BODY GENERATION FACILITIES ARE OFFLINE, the voice announced, sounding even more desolate than before. THERE ARE NO VIABLE TUTORIAL STARTING POINTS AVAILABLE FOR ASPIRANT ARRIVAL.
"Hold on," I told it. "If everything is offline, what does that mean for me? Am I stuck in this silver liquid shape forever?"
INITIATING EMERGENCY OVERRIDE, the flame replied, its color stabilizing into steady blue. SEARCHING FOR UNGUIDED NATURAL VESSELS... MATCH FOUND. A VIABLE ORGANIC VESSEL IS CURRENTLY FORMING IN THE PHYSICAL REALM WITHOUT EIDOLITH INTERVENTION. I AM READY TO INITIATE TRANSFER NOW. CONFIRM, PLEASE.
I frowned. A viable organic vessel forming in the physical realm? It sounded like the program was bypassing its broken infrastructure to hijack a naturally occurring event. I had a creeping suspicion about what that actually meant, but I couldn't see any other shot at moving forward.
I nodded. "Alright, I confirm."
ASTRAL TETHER INITIALIZED.
A silver cord emerged from what would be the base of my skull and shot off into the darkness, stretching out toward infinity.
TRANSMITTING, the fire boomed, its warmth washing over me one last time. MAY YOU RISE TO THE OCCASION, ASPIRANT.
Something started to pull on me. The silver thread went taut and trembled like a heavy fishing line fighting a strong current. I was drawn toward the distant terminus at a tremendous speed, leaving the fire and the lonely darkness behind.
""",
)

